import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

export const SOURCE_COMMIT =
  "ca96624a56bd078437bca8184e78163e5039ad19";
export const SOURCE_URL =
  `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${SOURCE_COMMIT}/geojson/ne_110m_land.geojson`;
export const SOURCE_SHA256 =
  "9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9";

const radians = (degrees) => (degrees * Math.PI) / 180;
const fract = (value) => value - Math.floor(value);
const hash = (a, b) =>
  fract(Math.sin(a * 127.1 + b * 311.7) * 43758.5453123);

function pointInRing([x, y], ring) {
  let inside = false;
  for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index++) {
    const [xi, yi] = ring[index];
    const [xj, yj] = ring[previous];
    const crosses =
      yi > y !== yj > y &&
      x < ((xj - xi) * (y - yi)) / (yj - yi || Number.EPSILON) + xi;
    if (crosses) inside = !inside;
  }
  return inside;
}

export function pointInPolygon(point, polygon) {
  return (
    pointInRing(point, polygon[0]) &&
    !polygon.slice(1).some((hole) => pointInRing(point, hole))
  );
}

function polygons(geojson) {
  return geojson.features.flatMap(({ geometry }) => {
    if (geometry.type === "Polygon") return [geometry.coordinates];
    if (geometry.type === "MultiPolygon") return geometry.coordinates;
    return [];
  });
}

export function sampleLand(
  geojson,
  { latitudeStep = 3.75, surfaceStep = 3.75 } = {},
) {
  const land = polygons(geojson);
  const samples = [];
  let row = 0;
  for (
    let latitude = -82.5;
    latitude <= 82.5 + 1e-6;
    latitude += latitudeStep, row++
  ) {
    const circumference = Math.max(0.28, Math.cos(radians(latitude)));
    const longitudeStep = surfaceStep / circumference;
    const columns = Math.max(1, Math.round(360 / longitudeStep));
    for (let column = 0; column < columns; column++) {
      const longitude = -180 + ((column + 0.5) * 360) / columns;
      if (
        !land.some((polygon) =>
          pointInPolygon([longitude, latitude], polygon),
        )
      )
        continue;
      samples.push({
        longitude,
        latitude,
        row,
        phase: hash(longitude * 0.1, latitude * 0.1),
        density: hash(longitude * 0.23 + 7, latitude * 0.19 - 3),
      });
    }
  }
  const lastRow = Math.max(1, row - 1);
  return samples.map((sample) => ({
    ...sample,
    row: sample.row / lastRow,
  }));
}

export function packSamples(samples) {
  return samples.flatMap(
    ({ longitude, latitude, row, phase, density }) => {
      const phi = radians(latitude);
      const theta = radians(longitude);
      const latitudeRadius = Math.cos(phi);
      return [
        latitudeRadius * Math.cos(theta),
        Math.sin(phi),
        latitudeRadius * Math.sin(theta),
        row,
        phase,
        density,
      ];
    },
  );
}

export async function prepareEarth({
  fetchImpl = fetch,
  output = "src/earth-data.js",
} = {}) {
  const response = await fetchImpl(SOURCE_URL);
  if (!response.ok)
    throw new Error(`Natural Earth download failed: ${response.status}`);
  const bytes = new Uint8Array(await response.arrayBuffer());
  const digest = createHash("sha256").update(bytes).digest("hex");
  if (digest !== SOURCE_SHA256)
    throw new Error(`Natural Earth checksum mismatch: ${digest}`);
  const packed = packSamples(
    sampleLand(JSON.parse(new TextDecoder().decode(bytes))),
  );
  const numbers = packed
    .map((value) => Number(value.toFixed(7)))
    .join(",");
  const source =
    "// Generated by npm run prepare:earth from Natural Earth 1:110m land.\n" +
    "export const EARTH_SAMPLE_STRIDE=6;\n" +
    `export const EARTH_SAMPLE_COUNT=${packed.length / 6};\n` +
    `export const EARTH_SAMPLES=new Float32Array([${numbers}]);\n`;
  await writeFile(output, source);
  return packed.length / 6;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const count = await prepareEarth();
  console.log(`Wrote ${count} land samples to src/earth-data.js`);
}
